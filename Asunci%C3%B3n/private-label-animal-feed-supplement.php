            const faqItems = document.querySelectorAll('.vpro-faq-item');
            faqItems.forEach(item => {
                const question = item.querySelector('.vpro-faq-question');
                question.addEventListener('click', () => {
                    // Close all other items
                    faqItems.forEach(otherItem => {
                        if (otherItem !== item) {
                            otherItem.classList.remove('active');
                        }
                    });
                    
                    // Toggle current item
                    item.classList.toggle('active');
                });
            });
            
            // Option Buttons
            const optionButtons = document.querySelectorAll('.vpro-option-btn');
            optionButtons.forEach(button => {
                button.addEventListener('click', function() {
                    // Remove active class from siblings
                    const parent = this.parentElement;
                    parent.querySelectorAll('.vpro-option-btn').forEach(btn => {
                        btn.classList.remove('active');
                    });
                    
                    // Add active class to clicked button
                    this.classList.add('active');
                });
            });
            
            // Quantity Selector
            const minusBtn = document.querySelector('.vpro-minus');
            const plusBtn = document.querySelector('.vpro-plus');
            const quantityInput = document.querySelector('.vpro-quantity-input');
            
            if (minusBtn && plusBtn && quantityInput) {
                minusBtn.addEventListener('click', function(e) {
                    e.preventDefault();
                    let currentVal = parseInt(quantityInput.value);
                    if (currentVal > parseInt(quantityInput.min)) {
                        quantityInput.value = currentVal - 1;
                    }
                });
                
                plusBtn.addEventListener('click', function(e) {
                    e.preventDefault();
                    let currentVal = parseInt(quantityInput.value);
                    if (currentVal < parseInt(quantityInput.max)) {
                        quantityInput.value = currentVal + 1;
                    }
                });
            }
            
            // Wishlist Button
            const wishlistBtn = document.querySelector('.vpro-wishlist-btn');
            if (wishlistBtn) {
                wishlistBtn.addEventListener('click', function() {
                    this.classList.toggle('active');
                    const icon = this.querySelector('i');
                    
                    if (this.classList.contains('active')) {
                        icon.classList.remove('far');
                        icon.classList.add('fas');
                        showToast('Added to wishlist!');
                    } else {
                        icon.classList.remove('fas');
                        icon.classList.add('far');
                        showToast('Removed from wishlist');
                    }
                });
            }
            
            // Toast Notification
            function showToast(message, type = 'success') {
                const toast = document.createElement('div');
                toast.className = `vpro-toast vpro-toast-${type}`;
                toast.textContent = message;
                
                // Style the toast
                toast.style.position = 'fixed';
                toast.style.bottom = '20px';
                toast.style.left = '50%';
                toast.style.transform = 'translateX(-50%)';
                toast.style.backgroundColor = type === 'error' ? '#e63946' : '#00aeb7';
                toast.style.color = 'white';
                toast.style.padding = '12px 24px';
                toast.style.borderRadius = '8px';
                toast.style.zIndex = '10000';
                toast.style.boxShadow = '0 4px 12px rgba(0,0,0,0.15)';
                toast.style.animation = 'vproToastFadeIn 0.3s ease-out';
                
                document.body.appendChild(toast);
                
                // Auto-remove after 3 seconds
                setTimeout(() => {
                    toast.style.animation = 'vproToastFadeOut 0.3s ease-out';
                    setTimeout(() => {
                        if (document.body.contains(toast)) {
                            document.body.removeChild(toast);
                        }
                    }, 300);
                }, 3000);
            }
            
            // Add toast styles dynamically
            const style = document.createElement('style');
            style.textContent = `
                @keyframes vproToastFadeIn {
                    from { opacity: 0; transform: translateX(-50%) translateY(20px); }
                    to { opacity: 1; transform: translateX(-50%) translateY(0); }
                }
                @keyframes vproToastFadeOut {
                    from { opacity: 1; transform: translateX(-50%) translateY(0); }
                    to { opacity: 0; transform: translateX(-50%) translateY(20px); }
                }
